def get_categories_for_okved(okved_code: str | None) -> list[str]:
    """Возвращает список общих категорий для проверки по коду ОКВЭД."""
    categories = list(UNIVERSAL_CATEGORIES)

    prefix = (okved_code or "")[:2]
    extra = CATEGORIES_BY_OKVED_PREFIX.get(prefix, DEFAULT_CATEGORIES)
    categories.extend(extra)

    return categories
